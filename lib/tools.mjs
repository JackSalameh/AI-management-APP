// Desktop tool integrations: VS Code and MATLAB discovery and launching.
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { which, fileExists, launchDetached, resolveLaunch } from './proc.mjs';

const isWin = process.platform === 'win32';
const isMac = process.platform === 'darwin';

// ---------------- VS Code ----------------
export function findVSCode(setting, env = process.env) {
  const tries = [];
  if (setting) tries.push(setting);
  if (isWin) {
    const la = env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local');
    tries.push(path.join(la, 'Programs', 'Microsoft VS Code', 'Code.exe'),
      path.join(env.ProgramFiles || 'C:\\Program Files', 'Microsoft VS Code', 'Code.exe'),
      path.join(la, 'Programs', 'cursor', 'Cursor.exe'));
  } else if (isMac) {
    tries.push('/Applications/Visual Studio Code.app/Contents/Resources/app/bin/code', path.join(os.homedir(), 'Applications/Visual Studio Code.app/Contents/Resources/app/bin/code'));
  }
  for (const t of tries) { const p = which(t, env); if (p) return p; }
  for (const c of ['code', 'code-insiders', 'codium', 'cursor']) {
    const p = which(c, env);
    if (!p) continue;
    // On Windows `code.cmd` lives in <install>\bin; prefer the real Code.exe one level up.
    if (isWin && /\.cmd$/i.test(p)) { const exe = path.join(path.dirname(p), '..', path.basename(p, '.cmd') === 'code' ? 'Code.exe' : 'Code - Insiders.exe'); if (fileExists(exe)) return path.normalize(exe); }
    return p;
  }
  return null;
}

export async function openInVSCode(setting, folder, { file, line } = {}) {
  const exe = findVSCode(setting);
  if (!exe) throw new Error('VS Code was not found. Install it, or set the path to Code.exe / code in Configuration › VS Code.');
  const args = [folder];
  if (file) args.push('--goto', line ? `${file}:${line}` : file);
  const launch = resolveLaunch(exe);
  await launchDetached(launch, args, { cwd: folder });
  return exe;
}

// ---------------- MATLAB ----------------
/** Lists installed MATLAB releases, newest first: [{ release: 'R2026a', exe }]. */
export function findMatlabInstalls(env = process.env) {
  const out = [];
  const add = (release, exe) => { if (fileExists(exe) && !out.some((o) => o.exe === exe)) out.push({ release, exe }); };
  const scan = (dir, exeOf) => { try { for (const d of fs.readdirSync(dir)) { const m = /R(20\d\d[ab])/.exec(d); if (m) add('R' + m[1], exeOf(path.join(dir, d))); } } catch { /* absent */ } };
  if (isWin) {
    for (const pf of [env.ProgramFiles || 'C:\\Program Files', env['ProgramFiles(x86)']].filter(Boolean)) scan(path.join(pf, 'MATLAB'), (d) => path.join(d, 'bin', 'matlab.exe'));
  } else if (isMac) {
    scan('/Applications', (d) => path.join(d, 'bin', 'matlab'));
  } else {
    for (const base of ['/usr/local/MATLAB', '/opt/MATLAB', path.join(os.homedir(), 'MATLAB')]) scan(base, (d) => path.join(d, 'bin', 'matlab'));
  }
  const onPath = which('matlab', env);
  if (onPath) { const m = /R(20\d\d[ab])/.exec(onPath); add(m ? 'R' + m[1] : 'PATH', onPath); }
  return out.sort((a, b) => b.release.localeCompare(a.release));
}

export function pickMatlab(cfg, env = process.env) {
  if (cfg.executable && fileExists(cfg.executable)) return { release: cfg.release || 'custom', exe: cfg.executable };
  const all = findMatlabInstalls(env);
  return (cfg.release && all.find((i) => i.release.toLowerCase() === cfg.release.toLowerCase())) || all[0] || null;
}

const mq = (s) => String(s).replace(/'/g, "''"); // MATLAB single-quote escaping

/**
 * The startup commands go into a generated .m file rather than onto the command line, so no quoting is
 * lost between the launcher, Windows and MATLAB (bug #4 of v1: `version(-release)`).
 */
export function matlabStartupScript({ folder, initSimulink, shareSession, runSetup }) {
  return [
    '% Generated by AI Management APP. Safe to delete.',
    'try',
    `    cd('${mq(folder)}');`,
    initSimulink ? [
      "    satk = fullfile(char(java.lang.System.getProperty('user.home')), '.matlab', 'agentic-toolkits', 'simulink');",
      "    if isfolder(satk), addpath(satk); if exist('satk_initialize', 'file'), satk_initialize; end, end",
    ].join('\n') : null,
    shareSession ? "    if exist('shareMATLABSession', 'file'), shareMATLABSession; end" : null,
    runSetup ? "    if exist('setupAgenticToolkit', 'file'), setupAgenticToolkit('install'); else, disp('[CPM] MathWorks Agentic Toolkit Setup is not installed (Add-On Explorer).'); end" : null,
    "    fprintf('[CPM] MATLAB %s ready in %s\\n', version('-release'), pwd);",
    'catch cpmErr',
    "    fprintf(2, '[CPM] Startup problem: %s\\n', cpmErr.message);",
    'end',
  ].filter(Boolean).join('\n') + '\n';
}

export async function launchMatlab(cfg, folder, dataDir, { runSetup = false } = {}) {
  const inst = pickMatlab(cfg);
  if (!inst) throw new Error(`MATLAB${cfg.release ? ' ' + cfg.release : ''} was not found. Set its executable in Configuration › MATLAB.`);
  const dir = path.join(dataDir, 'matlab');
  await fsp.mkdir(dir, { recursive: true });
  const script = path.join(dir, 'cpm_startup.m');
  await fsp.writeFile(script, matlabStartupScript({ folder, initSimulink: !!cfg.initSimulink, shareSession: cfg.shareSession !== false, runSetup }));
  const args = ['-sd', folder, '-r', `run('${mq(script)}')`];
  await launchDetached(resolveLaunch(inst.exe), args, { cwd: folder });
  return inst;
}
